os.makedirs('resultados_cafe', exist_ok=True)

# 1. Salvar planilha Excel multi-abas com todos os dados e métricas
excel_path = 'resultados_cafe/analise_quantitativa_cafe.xlsx'
with pd.ExcelWriter(excel_path, engine='openpyxl') as writer:
    metricas_financeiras.to_excel(writer, sheet_name='Metricas_Financeiras')
    metricas_macro.to_excel(writer, sheet_name='Metricas_Macro')
    metricas_ml.to_excel(writer, sheet_name='Metricas_ML')
    df_prev.to_excel(writer, sheet_name='Previsao_5_Anos')
    df_ts.to_excel(writer, sheet_name='Serie_Historica_Tratada')

# 2. Salvar gráficos interativos em HTML (abrem em qualquer navegador sem precisar de Python)
fig1.write_html('resultados_cafe/1_projecao_holt_winters.html')
